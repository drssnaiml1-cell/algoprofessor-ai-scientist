def tex_escape(s):
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$")]:
        s = s.replace(a, b)
    s = re.sub(r"`([^`]+)`", r"\\texttt{\1}", s)
    s = s.replace("→", r"$\rightarrow$").replace("±", r"$\pm$").replace("×", r"$\times$").replace("–", "--").replace("—", "---")
    s = s.replace("‘", "`").replace("’", "'").replace("“", "``").replace("”", "''")
    s = re.sub(r'"([^"]+)"', r"``\1''", s)
    s = s.replace(">", r"$>$")
    return s

def render_tex(n, w):
    L = [r"\clearpage", r"\section*{Monday--Saturday Project Homework: " + tex_escape(w["project"]) + "}",
         r"\addcontentsline{toc}{section}{Monday--Saturday Project Homework}",
         r"\begin{tcolorbox}[enhanced,colback=navy,colframe=gold,boxrule=0.8pt,arc=3pt,coltext=white,left=8pt,right=8pt,top=6pt,bottom=6pt]",
         r"{\color{gold}\bfseries Weekly project.} " + tex_escape(w["why"]) + r"\\[3pt]",
         r"{\color{gold}\bfseries Data:} " + tex_escape(w["dataset"]) + r"\\[3pt]",
         r"{\color{gold}\bfseries Rhythm:} about 2--3 hours a day. Commit every day; tag \texttt{week-" + str(n) +
         r"} and create a GitHub Release by \textbf{Saturday 23:59 local time}. Mentors review it before the next Sunday.",
         r"\end{tcolorbox}", ""]
    for d, (title, goal, tasks, deliv, accept, stretch, hours) in zip(DAYS, w["days"]):
        L += [r"\begin{tcolorbox}[enhanced,breakable,colback=white,colframe=sun,boxrule=0.8pt,arc=2pt,left=7pt,right=7pt,top=4pt,bottom=4pt,",
              r"  title={\bfseries " + d + r" --- " + tex_escape(title) + r"\hfill\normalfont\small " + tex_escape(hours) + r"},coltitle=white,colbacktitle=sun,fonttitle=\small]",
              r"\textbf{Goal.} " + tex_escape(goal), r"\begin{enumerate}[itemsep=1pt,topsep=2pt]"]
        L += [r"  \item " + tex_escape(t) for t in tasks]
        L += [r"\end{enumerate}",
              r"\textbf{\color{dataC}Deliverable:} " + tex_escape(deliv) + r"\\",
              r"\textbf{\color{navy}Done when:} " + tex_escape(accept) + r"\\",
              r"\textbf{\color{skillC}Stretch:} " + tex_escape(stretch),
              r"\end{tcolorbox}", ""]
    return "\n".join(L) + "\n"

