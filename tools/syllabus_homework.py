"""Render the 'Weekly Project Homework' section of the syllabus from tools/homework.py.
Usage: python3 tools/syllabus_homework.py   -> writes syllabus/homework_section.tex"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
src = (HERE / "homework.py").read_text()
ns = {"__file__": str(HERE / "homework.py")}
exec(src.split("\nfor n, w in WEEKS.items():")[0], ns)   # load data + helpers, skip file writing
WEEKS, DAYS, esc = ns["WEEKS"], ns["DAYS"], ns["tex_escape"]
COL = "ABCDEF"
SHORT = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]

L = [r"%% Generated by tools/syllabus_homework.py from tools/homework.py -- edit the source, not this file.",
     r"\section{Weekly Project Homework (Monday--Saturday)}\label{sec:homework}",
     r"\begin{navynote}",
     r"\textbf{\color{gold}How the week works.} Sunday teaches the method on a guided dataset; Monday to Saturday you apply it "
     r"to a harder, real dataset as one portfolio project. Plan \textbf{2--3 hours a day} (about 15 hours a week). "
     r"Commit every day, then tag \texttt{week-N} and create a GitHub Release by \textbf{Saturday 23:59 local time}. "
     r"Mentors review every release before the next Sunday and open the class with common mistakes. "
     r"Full daily task lists, acceptance checks and stretch goals are in each week's \texttt{HOMEWORK.md} and at the end of that Sunday's student notes.",
     r"\end{navynote}", ""]

for n, w in WEEKS.items():
    c = "sun" + COL[n - 1]
    L += [r"\begin{tcolorbox}[enhanced,breakable,colback=white,colframe=" + c + r",boxrule=0.9pt,arc=3pt,left=6pt,right=6pt,top=5pt,bottom=5pt,",
          r"  title={\sffamily\bfseries Week " + str(n) + r" homework\quad\normalfont\color{gold}$\cdot$\quad\color{white}" + esc(w["project"]) + r"},",
          r"  coltitle=white,colbacktitle=" + c + r",fonttitle=\sffamily]",
          r"{\small " + esc(w["why"]) + r"\\[2pt]\ds{Data:} " + esc(w["dataset"]) + r"}\par\smallskip",
          r"{\footnotesize\renewcommand{\arraystretch}{1.25}\rowcolors{2}{" + c + r"!6}{white}",
          r"\begin{tabularx}{\linewidth}{@{}L{0.07\linewidth} Y Y Y r@{}}",
          r"\rowcolor{" + c + r"}\color{white}\bfseries Day & \color{white}\bfseries Focus & \color{white}\bfseries Deliverable & \color{white}\bfseries Done when & \color{white}\bfseries Time\\"]
    for d, (title, goal, tasks, deliv, accept, stretch, hours) in zip(SHORT, w["days"]):
        L.append(r"\textbf{" + d + r"} & \textbf{" + esc(title) + r".} " + esc(goal) + " & " + esc(deliv) + " & " + esc(accept) + " & " + esc(hours) + r"\\")
    L += [r"\end{tabularx}}",
          r"\begin{goldnote}\textbf{Submit:} tag \texttt{week-" + str(n) + r"}, create a GitHub Release, and post the link by "
          r"{\color{saffron!80!black}\bfseries Saturday 23:59 local time}. Details: \texttt{" + esc(w["folder"]) + r"/HOMEWORK.md}.\end{goldnote}",
          r"\end{tcolorbox}", r"\vspace{4pt}", ""]

out = HERE.parent / "syllabus" / "homework_section.tex"
out.write_text("\n".join(L) + "\n")
print("wrote", out)
